import sympy as sp

# ============================================
# 2. FUNCIÓN GENERAL DE CENTRO DE MASA
# ============================================

def centro_de_masa(posiciones, masas):
    """
    posiciones: lista de tuplas o vectores (x,y) o (x,y,z)
    masas: lista de masas correspondientes

    Retorna: vector posición del centro de masa
    """
    if len(posiciones) != len(masas):
        raise ValueError("El número de posiciones y masas debe coincidir")

    # Convertimos todo a vectores sympy
    posiciones = [sp.Matrix(p) for p in posiciones]

    M_total = sum(masas)

    # Inicializamos la suma con un vector cero de las dimensiones correctas
    # para evitar TypeError al sumar un int con un sympy.Matrix.
    R_cm = sum((m * r for m, r in zip(masas, posiciones)), sp.zeros(posiciones[0].shape[0], 1)) / M_total

    return sp.simplify(R_cm)

