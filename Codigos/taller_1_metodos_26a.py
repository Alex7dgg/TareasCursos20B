def magnitud(v):
    return sp.sqrt(v.dot(v))

def angulo_info(v, w):
    cos_theta = sp.simplify(v.dot(w) / (magnitud(v)*magnitud(w)))
    theta = sp.acos(cos_theta)
    return cos_theta, theta

def proyeccion(v, w):
    return sp.simplify((v.dot(w)/w.dot(w)) * w)

def producto_triple(v1, v2, v3):
    return sp.simplify(v1.dot(v2.cross(v3)))

